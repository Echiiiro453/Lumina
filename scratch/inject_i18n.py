file_path = "e:/youtubr/youtubeMusicDownload-main/frontend/src/i18n.js"

with open(file_path, "r", encoding="utf-8") as f:
    content = f.read()

for lang_code, keys in translations.items():
    pattern = rf"({lang_code}:\s*{{.*?)(playerNoTrack:)"
    new_keys_str = "    // ── Newly Found Texts ──\n"
    for k, v in keys.items():
        # Escape single quotes in the JS output to prevent breaking JS
        safe_v = v.replace("'", "\\'")
        new_keys_str += f"    {k}: '{safe_v}',\n"
    new_keys_str += "\n    "
    
    content = re.sub(pattern, lambda m: m.group(1) + new_keys_str + m.group(2), content, flags=re.DOTALL)

with open(file_path, "w", encoding="utf-8") as f:
    f.write(content)

print("Injected translations successfully!")
