# For each language, find its block and remove existing keys to avoid duplicates, then inject.
for lang, keys in translations.items():
    # We will find the start of the block and the end of the block using standard matching
    # We look for the closing brace `  },` before the next block or at EOF.
    pattern = rf"(  {lang}:\s*\{{)(.*?)(  \}},|  \}})"
    match = re.search(pattern, i18n_content, flags=re.DOTALL)
    
    if match:
        prefix = match.group(1)
        block = match.group(2)
        suffix = match.group(3)
        
        # Remove our keys from this specific block only
        for k in keys.keys():
            block = re.sub(rf"^\s*{k}:\s*'.*?',\n", "", block, flags=re.MULTILINE)
        
        # Inject new keys right before the end
        new_keys_str = "    // ── Second Sweep Texts ──\n"
        for k, v in keys.items():
            safe_v = v.replace("'", "\\'")
            new_keys_str += f"    {k}: '{safe_v}',\n"
        
        block += "\n" + new_keys_str
            
        i18n_content = i18n_content[:match.start()] + prefix + block + suffix + i18n_content[match.end():]

with open(i18n_path, "w", encoding="utf-8") as f:
    f.write(i18n_content)

